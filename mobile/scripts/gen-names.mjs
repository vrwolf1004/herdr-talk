// Writes src/relay/names.ts from the name table in rust/crates/talk-core/src/chat.rs (NAMES_BY_LANGUAGE),
// so the phone and the PC editions suggest the same names. Run after the Rust table changes:
//   node scripts/gen-names.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const RUST_SOURCE = new URL("../../rust/crates/talk-core/src/chat.rs", import.meta.url);
const OUTPUT = new URL("../src/relay/names.ts", import.meta.url);

/** [language code, names] pairs from the Rust table, in the same order. */
export function parseNames(rustText) {
  const start = rustText.indexOf("pub const NAMES_BY_LANGUAGE");
  if (start < 0) throw new Error("NAMES_BY_LANGUAGE not found in chat.rs");
  const table = rustText.slice(start, rustText.indexOf("];", start));
  const rows = [...table.matchAll(/\("([a-z]+)", \[([^\]]*)\]\)/g)];
  return rows.map(([, code, list]) => [code, [...list.matchAll(/"([^"]*)"/g)].map((match) => match[1])]);
}

export function render(pairs) {
  const rows = pairs.map(([code, names]) => `  ["${code}", [${names.map((name) => JSON.stringify(name)).join(", ")}]],`);
  return [
    "// GENERATED by scripts/gen-names.mjs from rust/crates/talk-core/src/chat.rs. Do not edit by hand.",
    "",
    "export const NAMES_BY_LANGUAGE: ReadonlyArray<readonly [string, readonly string[]]> = [",
    ...rows,
    "];",
    "",
    "/** The names for a locale such as ko_KR or ko-KR. A language that is not listed gets every name, as talk-core does. */",
    "export function namesFor(locale: string): readonly string[] {",
    "  const language = locale.trim().toLowerCase();",
    "  const found = NAMES_BY_LANGUAGE.find(([code]) => language.startsWith(code));",
    "  return found ? found[1] : NAMES_BY_LANGUAGE.flatMap(([, names]) => names);",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, render(parseNames(readFileSync(RUST_SOURCE, "utf8"))));
  console.log("wrote src/relay/names.ts");
}
